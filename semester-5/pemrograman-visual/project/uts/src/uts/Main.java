    private void btnLogin1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLogin1ActionPerformed
        // TODO add your handling code here:
        String user = fieldUser1.getText();
        String pass = fieldPass1.getText();
        
        // Menampilkan notifikasi
        if (user.equals(registeredUser)) {
            if (pass.equals(registeredPass)) {
                JOptionPane.showMessageDialog(null, "Login success!");
                
                tabPanel.setEnabledAt(2, true); // Unlock tab dashboard
                tabPanel.setEnabledAt(3, true); // Unlock tab report list
                tabPanel.setEnabledAt(4, true); // Unlock tab add report
                tabPanel.setSelectedIndex(2); // Pindah ke tab dashboard ketika login berhasil
                
            } else {
                JOptionPane.showMessageDialog(null, "Wrong password!");
            }
        } else {
            JOptionPane.showMessageDialog(null, "Username is not registered!");
        }
        
        // Menampilkan sambutan pada dashboard
        lblWelcome2.setText("Welcome to our Lost & Found website, "+registeredFullName+"! Ready to report something?");
    }//GEN-LAST:event_btnLogin1ActionPerformed

    private void btnRegister0ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegister0ActionPerformed
        // TODO add your handling code here:
        // Menyimpan input dari field ke variabel global
        registeredUser = fieldUser0.getText();
        registeredPass = fieldPass0.getText();
        registeredFullName = fieldFullName0.getText();
        
        if(fieldPass0.getText().equals(fieldConfirm0.getText())&&
           !fieldFullName0.getText().equals("")&&!fieldStudentID0.getText().equals("")&&
           !fieldPass0.getText().equals("")&&!fieldConfirm0.getText().equals("")&&
           !fieldUser0.getText().equals("")
           ){
            String teks="";
            // Menentukan teks yang akan ditampilkan setelah regist berhasil
            teks+= "Full Name: "+fieldFullName0.getText()+"\n";
            teks+= "Student ID: "+fieldStudentID0.getText()+"\n";
            teks+= "Username: "+fieldUser0.getText()+"\n";
            teks+= "Password: "+fieldPass0.getText()+"\n";
            teks+= "Grade: ";
            // Menentukan jenis kelamin
            if(rbX.isSelected()){
                teks+= "10th Grade \n";
            }else if(rbXI.isSelected()){
                teks+= "11th Grade \n";
            }else{
                teks+= "12th Grade \n";
            }
            teks+= "Register success!\n";
            teks+= "Please remember these information when you are about to login";
            // Menampilkan pesan error jika field kosong
            JOptionPane.showMessageDialog(null, teks);
        }else if(fieldPass0.getText().equals("")||fieldConfirm0.getText().equals("")){
            JOptionPane.showMessageDialog(null, "Your password field is empty, please input your password!");
        }else if(fieldFullName0.getText().equals("")){
            JOptionPane.showMessageDialog(null, "Your name field is empty, please input your name!!");
        }else if(fieldStudentID0.getText().equals("")){
            JOptionPane.showMessageDialog(null, "Your student ID field is empty, please input your student ID!!");
        }else if(fieldUser0.getText().equals("")){
            JOptionPane.showMessageDialog(null, "Your username field is empty, please input your username!");
        }else{
            JOptionPane.showMessageDialog(null, "Your password and your confirmed password is not matched!");
        }
        tabPanel.setEnabledAt(1, true); // Unlock tab login
        tabPanel.setSelectedIndex(1); // Pindah ke tab login ketika register berhasil
    }//GEN-LAST:event_btnRegister0ActionPerformed

